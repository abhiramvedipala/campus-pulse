"""Generate docs/data-dictionary.md from dbt docs metadata (catalog.json + manifest.json) and raw.suppression."""

import json
import re
import subprocess
import sys

import duckdb

from campuspulse import config as C
from campuspulse import load

fixture = "--fixture" in sys.argv
subprocess.run(
    [sys.executable, "-m", "dbt.cli.main", "docs", "generate", "--profiles-dir", "."],
    cwd=C.ROOT / "dbt",
    check=True,
    stdout=subprocess.DEVNULL,
)
manifest = json.loads((C.ROOT / "dbt/target/manifest.json").read_text())
catalog = json.loads((C.ROOT / "dbt/target/catalog.json").read_text())
con = duckdb.connect(str(load.db_path(fixture)), read_only=True)
supp = con.sql("select release, column_name, n_rows, n_suppressed, n_nonnull from raw.suppression").df()
supp["release_year"] = supp.release.str[:4].astype(int)
MARTS = ["fct_institution_year", "dim_institution", "mart_sector_year", "mart_florida_publics", "mart_model_input"]


def availability(source_field: str):
    """Release years with data and PrivacySuppressed share, for raw Scorecard columns named in source_field."""
    cols = re.findall(r"\b[A-Z][A-Z0-9_]{2,}\b", source_field.replace("MERGED<release>_PP", ""))
    s = supp[supp.column_name.isin(cols)]
    if s.empty:
        return "n/a", "n/a", "n/a"
    yrs = sorted(s[s.n_nonnull > 0].release_year.unique())
    rate = s.groupby("release_year").n_suppressed.sum() / s.groupby("release_year").n_rows.sum()
    miss = 1 - s.groupby("release_year").n_nonnull.sum() / s.groupby("release_year").n_rows.sum()
    return (", ".join(map(str, yrs)) or "none"), f"{rate.min():.1%} to {rate.max():.1%}", f"{miss.min():.1%} to {miss.max():.1%}"


lines = [
    "# Data dictionary",
    "",
    "Generated by `scripts/build_dictionary.py` from dbt docs metadata; do not edit by hand.",
    "",
    "**How to read the years.** `release_year` is the first calendar year of a College Scorecard institution-level "
    "release (2011 = the 2011-12 file). The six releases are 2011, 2012, 2013, 2014, 2020 and 2022: these are the six most "
    "recent releases in which 10-year earnings (`MD_EARN_WNE_P10`) are populated (see DECISIONS.md D-02). Earnings describe a "
    "cohort that entered college about a decade before the release year, so they are not current-year outcomes. "
    "All dollar fields are nominal as published; Scorecard re-bases each release to a different year, so models use "
    "release-year fixed effects.",
    "",
    "**Suppression.** Scorecard writes `PrivacySuppressed` for small cells and `NULL`/`NA` for not reported. Two shares are given per "
    "column (range across releases). Missingness is not random: small institutions drop out.",
    "",
    "**Fields that are empty.** `CCBASIC` (Carnegie) is empty in all six releases, so Carnegie groups come from IPEDS HD. "
    "IPEDS derived files (DRVGR, DRVEF, DRVC) exist only for survey year 2022, so `ipeds_enrollment_total` and `ipeds_fte` "
    "are empty for the other five releases.",
    "",
]
for name in MARTS:
    node = manifest["nodes"][f"model.campus_pulse.{name}"]
    types = {k.lower(): v["type"] for k, v in catalog["nodes"][f"model.campus_pulse.{name}"]["columns"].items()}
    df = con.sql(f"select * from marts.{name}").df()
    by_year = df.isna().groupby(df["release_year"]).mean() if "release_year" in df else None
    lines += [
        f"## {name}",
        "",
        node["description"],
        "",
        "| Column | Type | Source field | Years with data | Suppressed (PS) share | Missing share in mart | Meaning | Caveat |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for col, meta in node["columns"].items():
        src = meta.get("meta", {}).get("source_field", "")
        yrs, rate, _ = availability(src) if src else ("n/a", "n/a", "n/a")
        miss = "n/a" if by_year is None or col not in by_year else f"{by_year[col].min():.1%} to {by_year[col].max():.1%}"
        cav = meta.get("meta", {}).get("caveat", "")
        lines.append(f"| `{col}` | {types.get(col, '')} | {src} | {yrs} | {rate} | {miss} | {meta['description']} | {cav} |")
    lines.append("")
missing = [
    n
    for n in MARTS
    for c in manifest["nodes"][f"model.campus_pulse.{n}"]["columns"]
    if c not in catalog["nodes"][f"model.campus_pulse.{n}"]["columns"]
    and c.upper() not in catalog["nodes"][f"model.campus_pulse.{n}"]["columns"]
]
undocumented = [
    (n, c)
    for n in MARTS
    for c in catalog["nodes"][f"model.campus_pulse.{n}"]["columns"]
    if c.lower() not in manifest["nodes"][f"model.campus_pulse.{n}"]["columns"]
]
assert not missing and not undocumented, (missing, undocumented)
(C.ROOT / "docs").mkdir(exist_ok=True)
(C.ROOT / "docs/data-dictionary.md").write_text("\n".join(lines))
print(
    "wrote docs/data-dictionary.md;",
    sum(len(manifest["nodes"][f"model.campus_pulse.{n}"]["columns"]) for n in MARTS),
    "mart columns documented",
)
